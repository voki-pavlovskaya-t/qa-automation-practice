# Напиши программу, которая:
#
# Задаёт переменную lives = 3 (количество жизней игрока).
# Запускает цикл while, который работает, пока у игрока есть жизни (lives > 0):
# На каждой итерации через input() спрашивай пользователя: "Игрок погиб? (да/нет): "
# Если ответ "да" — уменьшай lives на 1 и выводи сообщение с оставшимся количеством жизней.
# Если ответ "нет" — выводи сообщение "Раунд пройден успешно" и не уменьшай жизни.
# Если жизни закончились (lives == 0) — выведи "Game Over" и останови цикл.
#
# Используй: цикл while с условием выхода, input() с приведением к нужному виду сравнения, if/else, арифметику (-=).

lives = 3

while lives > 0:
    question = input("Игрок погиб? (да/нет):")
    if question == "да":
        lives -= 1
        if lives == 0:
            print("Game over")
            break
    elif question == "нет":
        print("Раунд пройден успешно")
